let currentLang = 'vi';

/**
 * Switch current language
 * @param {string} langCode 
 */
function setLanguage(langCode) {
  if (!I18N_DICTIONARY[langCode]) langCode = 'vi';
  currentLang = langCode;
  localStorage.setItem('minex_lang', langCode);

  const langObj = I18N_LANGUAGES.find(l => l.code === langCode) || I18N_LANGUAGES[0];

  // Update button display
  const elFlag = document.getElementById('langCurrentFlag');
  const elName = document.getElementById('langCurrentName');
  if (elFlag) elFlag.innerText = langObj.flag;
  if (elName) elName.innerText = langObj.name;

  // Apply translations to DOM elements with data-i18n
  const currentDict = I18N_DICTIONARY[langCode] || I18N_DICTIONARY.vi;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const text = currentDict[key] || (I18N_DICTIONARY.vi && I18N_DICTIONARY.vi[key]);
    if (text) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = text;
      } else {
        el.innerText = text;
      }
    }
  });

  // Apply translations to placeholder elements with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (currentDict[key]) {
      el.placeholder = currentDict[key];
    }
  });

  // Apply translations to title tooltips with data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.dataset.i18nTitle;
    if (currentDict[key]) {
      el.title = currentDict[key];
    }
  });

  // Update active state in dropdown
  document.querySelectorAll('.lang-item').forEach(item => {
    if (item.dataset.lang === langCode) {
      item.classList.add('active');
    } else {
      item.classList.remove('active');
    }
  });

  // Refresh language modal list to highlight selected language
  renderLangModal();

  // Close dropdown if open
  closeLangDropdown();

  // Re-render Store Miners if function exists
  if (typeof window.renderStoreMiners === 'function') {
    window.renderStoreMiners();
  }

  // Update claim button countdown & notices with new language
  if (typeof window.updateClaimButtonState === 'function') {
    window.updateClaimButtonState();
  }

  // If user is logged in, refresh role text & UID
  if (typeof window.updateUserInterface === 'function') {
    window.updateUserInterface();
  }

  // If history filter function exists, refresh history table
  if (typeof window.filterHistory === 'function' && window.State && Array.isArray(window.State.transactions)) {
    const currentActiveFilter = document.querySelector('.tx-filter-btn.btn-primary');
    const activeType = currentActiveFilter ? currentActiveFilter.dataset.type : 'all';
    window.filterHistory(activeType);
  }

  // Dispatch custom languageChanged event
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: langCode, dict: currentDict } }));
}

/**
 * Render language modal list (for mobile modal popup)
 */
function renderLangModal() {
  const list = document.getElementById('langModalList');
  if (!list) return;

  list.innerHTML = '';
  I18N_LANGUAGES.forEach(item => {
    const isCurrent = (item.code === currentLang);
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = `lang-modal-btn ${isCurrent ? 'active' : ''}`;
    btn.onclick = (e) => {
      e.stopPropagation();
      selectLanguage(item.code);
    };

    btn.innerHTML = `
      <div style="display: flex; align-items: center; gap: 14px;">
        <span style="font-size: 1.6rem; line-height: 1;">${item.flag}</span>
        <div style="text-align: left;">
          <div style="font-size: 0.95rem; font-weight: 700; color: ${isCurrent ? '#dfc5b2' : '#ffffff'}; line-height: 1.3;">${item.name}</div>
          <div style="font-size: 0.74rem; color: #8e8c94;">${item.nativeName} (${item.short})</div>
        </div>
      </div>
      <div style="display: flex; align-items: center; justify-content: center; width: 26px; height: 26px; border-radius: 50%; background: ${isCurrent ? 'rgba(223, 197, 178, 0.25)' : 'rgba(255, 255, 255, 0.04)'};">
        <span style="font-size: 0.95rem; color: #dfc5b2; font-weight: 800; opacity: ${isCurrent ? '1' : '0'};">✓</span>
      </div>
    `;

    list.appendChild(btn);
  });
}

/**
 * Handle user selecting a language from modal
 */
function selectLanguage(code) {
  setLanguage(code);
  if (typeof window.closeModal === 'function') {
    window.closeModal('langModal');
  }
  closeLangDropdown();
  if (typeof window.showToast === 'function') {
    const langObj = I18N_LANGUAGES.find(l => l.code === code);
    window.showToast(`🌐 Đã chuyển sang ${langObj ? langObj.name : code}`, 'success');
  }
}

/**
 * Toggle Language Selector (Opens full modal or dropdown)
 */
function toggleLangDropdown(e) {
  if (e) {
    e.stopPropagation();
    e.preventDefault();
  }

  // 1. Prefer opening dedicated language modal (100% visible, never clipped or covered)
  const langModal = document.getElementById('langModal');
  if (langModal && typeof window.openModal === 'function') {
    renderLangModal();
    window.openModal('langModal');
    return;
  }

  // 2. Fallback to inline dropdown menu
  const dropdown = document.getElementById('langSelector');
  const menu = document.getElementById('langMenu');
  if (!menu || !dropdown) return;

  if (menu.style.display === 'none' || !menu.style.display) {
    renderLangMenu();
    menu.style.display = 'block';
    dropdown.classList.add('open');
  } else {
    menu.style.display = 'none';
    dropdown.classList.remove('open');
  }
}

function closeLangDropdown() {
  const dropdown = document.getElementById('langSelector');
  const menu = document.getElementById('langMenu');
  if (menu) menu.style.display = 'none';
  if (dropdown) dropdown.classList.remove('open');
}

/**
 * Render language menu items (desktop dropdown fallback)
 */
function renderLangMenu() {
  const menu = document.getElementById('langMenu');
  if (!menu) return;

  menu.innerHTML = '';
  I18N_LANGUAGES.forEach(item => {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = `lang-item ${item.code === currentLang ? 'active' : ''}`;
    btn.dataset.lang = item.code;
    btn.onclick = (e) => {
      e.stopPropagation();
      selectLanguage(item.code);
    };

    btn.innerHTML = `
      <div class="lang-item-left">
        <span style="font-size: 1.15rem; line-height: 1;">${item.flag}</span>
        <div>
          <span style="font-weight: 600; font-size: 0.84rem; display: block; line-height: 1.2;">${item.name}</span>
          <span style="font-size: 0.7rem; color: var(--text-dim);">${item.nativeName}</span>
        </div>
      </div>
      <span class="lang-check" style="font-size: 0.75rem; color: #dfc5b2; opacity: ${item.code === currentLang ? '1' : '0'};">✓</span>
    `;

    menu.appendChild(btn);
  });
}

/**
 * Initialize i18n
 */
function initI18n() {
  const savedLang = localStorage.getItem('minex_lang') || 'vi';
  renderLangMenu();
  renderLangModal();
  setLanguage(savedLang);

  // Close dropdown when clicking outside
  document.addEventListener('click', (e) => {
    const selector = document.getElementById('langSelector');
    if (selector && !selector.contains(e.target)) {
      closeLangDropdown();
    }
  });
}

